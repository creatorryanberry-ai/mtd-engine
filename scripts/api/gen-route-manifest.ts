#!/usr/bin/env bun

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'

const ROOT = resolve(import.meta.dir, '../..')
const API_DIR = join(ROOT, 'app/api')
const OUT = join(ROOT, 'src/server/routeManifest.generated.ts')
const METHODS = ['GET', 'POST', 'PATCH', 'PUT', 'DELETE'] as const

// web-tier routes the native-facing standalone api must NOT serve. `/api/og`
// renders OpenGraph images (satori + the native @resvg/resvg-js binding, remote
// font fetches, reads from public/) — a web/SSR concern the `one` web service keeps
// serving. excluding it keeps the api bundle free of web-only render deps.
const WEB_TIER_PATTERNS = new Set(['/api/og'])

function walk(dir: string): string[] {
  const out: string[] = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(p))
    else if (entry.name.endsWith('+api.ts') || entry.name.endsWith('+api.tsx'))
      out.push(p)
  }
  return out
}

function patternFor(file: string): string {
  const rel = relative(API_DIR, file).replace(/\+api\.tsx?$/, '')
  const segs = rel
    .split('/')
    .map((s) => s.replace(/^\[\.\.\.(.+)\]$/, '*').replace(/^\[(.+)\]$/, ':$1'))
  return `/api/${segs.join('/')}`.replace(/\/$/, '')
}

// NOTE: parse the route files as text rather than `await import(file)`.
// route modules transitively import `~/database/db` which does `import 'server-only'`,
// and `server-only` throws under plain `bun run` (no react-server condition). the
// generated manifest still statically imports them — that file is only ever bundled
// with `--conditions react-server` (api:build) or type-checked, never executed here.
function main() {
  const files = walk(API_DIR).sort()
  const imports: string[] = []
  const entries: string[] = []

  for (const [i, file] of files.entries()) {
    const src = readFileSync(file, 'utf8')
    const present = METHODS.filter((m) =>
      new RegExp(`export\\s+const\\s+${m}\\b`).test(src),
    )
    // a bare `export default` handler is One's catch-all: it receives every method
    // and gates internally (e.g. file/upload+api.ts returns 405 for non-POST). mirror
    // that by registering the default export under every method.
    const hasDefault = present.length === 0 && /export\s+default\b/.test(src)
    if (present.length === 0 && !hasDefault) continue
    const pattern = patternFor(file)
    if (WEB_TIER_PATTERNS.has(pattern)) continue
    const rel = relative(join(ROOT, 'src/server'), file).replace(/\.tsx?$/, '')
    const alias = `r${i}`
    imports.push(`import * as ${alias} from '${rel}'`)
    const methodEntries = hasDefault ? METHODS : present
    for (const m of methodEntries) {
      const ref = hasDefault ? `${alias}.default` : `${alias}.${m}`
      entries.push(`  { method: '${m}', pattern: '${pattern}', handler: ${ref} },`)
    }
  }

  const body = `// GENERATED by scripts/api/gen-route-manifest.ts — do not edit by hand.
// run: bun run api:manifest
import type { ApiRoute } from './router'

${imports.join('\n')}

export const apiRouteManifest: ApiRoute[] = [
${entries.join('\n')}
]
`
  writeFileSync(OUT, body)
  console.info(`[api] wrote ${entries.length} routes to ${relative(ROOT, OUT)}`)
}

main()
